"use client";

import { useState } from "react";
import NoticeDialog, {
  NoticeSection as Section,
} from "@/components/NoticeDialog";

/**
 * How AI was used to make this app — a diligence statement, modelled on the
 * transparency practice in Anthropic's AI Fluency course: say which tools were
 * used, for what, and who checked and stands behind the result.
 *
 * Sits beside the privacy link in the AiDisclaimer footer and opens in place
 * for the same reason that one does.
 *
 * Every claim here is about authorship, so it must stay true as the app
 * changes. If a new philosopher, course, or asset is made differently from
 * what is described below, this changes with it and the date moves.
 */

/** Shown at the foot of the statement; bump when the substance changes. */
const LAST_UPDATED = "27 October 2026";

/** Highlighted run of text, matching the privacy notice's emphasis. */
function Em({ children }: { children: React.ReactNode }) {
  return <span className="text-parchment">{children}</span>;
}

function AiUseDialog({ onClose }: { onClose: () => void }) {
  return (
    <NoticeDialog
      id="ai-use-notice"
      title="How AI was used"
      closeLabel="Close AI use statement"
      onClose={onClose}
    >
      <p className="mt-4 rounded-lg border border-ink-700 bg-ink-800/60 p-3 text-[13px] leading-relaxed text-parchment">
        Overall, AI was used in this project for coding, research, and
        proofreading. The UI design of the app was created entirely by me and
        was illustrated by paper sketches and uploaded to Claude Code and Codex
        to implement. Research was done by AI for some philosophers, which was
        proofread and corrected by me, and AI acted as a thought partner for
        persona prompts with me being the final judge on what was actually
        used. AI is used for generating responses by the philosophers.
      </p>

      <Section title="What you are talking to">
        <p>
          The philosophers in conversations and debates are{" "}
          <Em>AI simulations, not the people themselves</Em>. Their replies are
          written live by Anthropic&rsquo;s Claude (Claude Opus 4.8 by default),
          following instructions about each philosopher&rsquo;s ideas and
          manner of speaking. A simulation can paraphrase loosely, misremember a
          detail, or state an interpretation more confidently than scholars
          would. Treat what they say as a way into the ideas, and check anything
          that matters against the philosopher&rsquo;s own writing.
        </p>
      </Section>

      <Section title="The courses">
        <p>
          Every word of a course lecture was <Em>written by me</Em>. The ideas,
          the structure, and the examples are mine. Where I used AI at all, it
          was as a thought partner — talking through how to explain a hard idea
          more clearly — never to write or design a lesson. Every student hears
          the same script.
        </p>
        <p>
          The one place AI speaks inside a course is when you{" "}
          <Em>interrupt with a question</Em>. That answer is generated by Claude
          in the lecturer&rsquo;s voice, and the lecture then resumes from the
          line where it stopped. The lecture is mine; the answer to your
          interruption is not.
        </p>
      </Section>

      <Section title="The philosophers">
        <p>
          For each philosopher I decided who they should be — Hume sardonic and
          playful, Plato thoughtful and serious — and Claude wrote the detailed
          instructions that carry that out. I treated Claude as a thought
          partner here, not the decision-maker:{" "}
          <Em>I had the final say on every persona</Em>.
        </p>
        <p>
          The profile introductions were written two ways, depending on what I
          already knew. For philosophers I know well — Kierkegaard, Sartre,
          Heidegger, Girard, Nietzsche — I wrote the introductions and used AI
          to refine them. For philosophers I knew less well, such as
          Wittgenstein and Epicurus, AI drafted them and I checked and verified
          them.
        </p>
        <p>
          Research for the profiles used Claude and ChatGPT. I relied on that
          research less for the philosophers I already knew, and in every case I
          reviewed what the AI produced and confirmed the facts myself.
        </p>
        <p>
          Claude also built the reference notes the simulations draw on:
          summaries of each philosopher&rsquo;s positions, based on sources such
          as the Stanford Encyclopedia of Philosophy and the philosophers&rsquo;
          own works.
        </p>
      </Section>

      <Section title="Why Should I Care About Philosophy?">
        <p>
          This section is <Em>entirely my own work</Em>. I deliberately kept AI
          out of it, except for proofreading and suggestions on the writing.
        </p>
      </Section>

      <Section title="The diagnostic quiz">
        <p>
          AI helped build the diagnostic quiz, including drafting questions and
          designing how answers are scored.
        </p>
      </Section>

      <Section title="Voices">
        <p>
          Spoken replies use voices from <Em>ElevenLabs</Em>, or your
          browser&rsquo;s built-in voice when that is unavailable. The voices
          for Sartre, de Beauvoir, and Heidegger were designed to evoke how
          those philosophers sounded, using written descriptions I prepared with
          help from AI. <Em>No voice was cloned</Em>, and no recording of any
          real person was used to make them.
        </p>
      </Section>

      <Section title="Images">
        <p>
          The portraits in the philosopher carousel are real photographs and
          artworks from <Em>Wikimedia Commons</Em>, used under their licences.
          The large hero portraits are <Em>AI-generated</Em>, created by ChatGPT
          from reference images of each philosopher.
        </p>
      </Section>

      <Section title="The design and the code">
        <p>
          I designed the interface and every page, sketching how each should
          look and behave. <Em>Claude Code and Codex wrote the code</Em> that
          implements those designs. The AI ran tests as it built each feature, and I tested
          the app myself before anything shipped.
        </p>
      </Section>

      <Section title="Responsibility">
        <p>
          AI did a great deal of work on this app, but the decisions were mine,
          and so is the responsibility. If something here is wrong — a
          misattributed idea, a mistaken fact, a voice that crosses a line —
          that is on me to fix, not on the tools.
        </p>
      </Section>

      <p className="mt-6 border-t border-ink-700 pt-3 text-[11px] text-muted">
        Last updated {LAST_UPDATED}.
      </p>
    </NoticeDialog>
  );
}

/**
 * The link itself. Inherits type styling from whatever it sits in, so it reads
 * as the next item in the disclosure rather than a control bolted underneath.
 */
export default function AiUseNotice({
  className = "",
}: {
  className?: string;
}) {
  const [open, setOpen] = useState(false);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className={`underline decoration-ink-600 underline-offset-2 transition duration-150 hover:text-parchment hover:decoration-parchment ${className}`}
      >
        How AI was used
      </button>
      {open && <AiUseDialog onClose={() => setOpen(false)} />}
    </>
  );
}
